"""LaTeX for the replacement Tables VI and VII and the maintenance table, straight from results/*.json.

Usage: python experiments/make_latex.py  ->  results/latex_tables.tex
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORDER = ["FW", "SDBN", "PF", "NC", "API"]
EXTRA = ["NC0", "ORACLE"]


def num(n: int) -> str:
    """Thousands separator in LaTeX form: 9990 -> 9{,}990."""
    return f"{n:,}".replace(",", "{,}")


def pct(x: float) -> str:
    """Percentage with two decimals below 1%, so 0.07% does not print as 0.1."""
    return f"{100 * x:.2f}" if 0 < 100 * x < 1 else f"{100 * x:.1f}"


def pm(r, k, nd=2):
    return f"{r[k]['mean']:.{nd}f} $\\pm$ {r[k]['sd']:.{nd}f}"


def table6(res: dict) -> str:
    n_cases = res["models"]["API"]["N_cases"]
    n_pipes = res["models"]["API"]["N_pipelines"]
    rows = []
    for m in ORDER + EXTRA:
        r = res["models"][m]
        name = r["name"].replace("w/o", "w/o")
        if m == "ORACLE":
            name = "Oracle (true parameters)$^\\dagger$"
        if m == "NC0":
            name = "No coupling, w/o MCMC$^\\ddagger$"
        rows.append(f"{name} & {pm(r, 'MAE')} & {pm(r, 'RMSE')} & {pm(r, 'CRPS')} & "
                    f"{pm(r, 'Brier', 3)} & {100 * r['PICP_pooled']:.1f} \\\\")
        if m == "API":
            rows.append("\\midrule")
    return "\n".join([
        "\\begin{table}[!t]",
        "\\centering",
        f"\\caption{{RUL prediction performance (mean $\\pm$ s.d. over {res['n_seeds']} matched runs;"
        f" {num(n_pipes)} test pipelines, {num(n_cases)} forecasts per model)}}",
        "\\label{tab:rul}",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "Model & MAE (yr) & RMSE (yr) & CRPS (yr) & Brier & PICP (\\%) \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\\\[2pt]\\footnotesize{Brier: failure within 2~yr. PICP: pooled coverage of the central 95\\% interval.",
        "$^\\dagger$Reference only: knows the true parameters.",
        " $^\\ddagger$Completes the factorial of Table~\\ref{tab:ablation}.}",
        "\\end{table}",
    ])


def table7(res: dict) -> str:
    g = {k: res["models"][k]["MAE"]["mean"] for k in ("NC0", "PF", "NC", "API")}
    return "\n".join([
        "\\begin{table}[!t]",
        "\\centering",
        "\\caption{Ablation of the adaptive model (MAE, yr). All four configurations update states"
        " and parameters sequentially.}",
        "\\label{tab:ablation}",
        "\\begin{tabular}{lcc}",
        "\\toprule",
        " & Coupling off & Coupling on \\\\",
        "\\midrule",
        f"MCMC off & {g['NC0']:.2f} & {g['PF']:.2f} \\\\",
        f"MCMC on & {g['NC']:.2f} & {g['API']:.2f} \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ])


def maintenance(res: dict) -> str:
    names = {"SDBN": "Static DBN", "API": "API-DBN", "ORACLE": "Oracle (true parameters)"}
    rows = []
    for m in ("SDBN", "API", "ORACLE"):
        o = res["models"][m]["optimum"]
        pp = res["models"][m]["paper_policy_I2_g1.5"]
        rows.append(f"{names[m]} & {o['I']:.1f} & {o['gamma']:.1f} & {o['cost_k$']:.1f} $\\pm$ {o['se_k$']:.1f} & "
                    f"{pct(o['P_any_failure'])} & {pp['cost_k$']:.1f} & {pct(pp['P_any_failure'])} \\\\")
    n = res["models"]["API"]["n_pipelines"]
    return "\n".join([
        "\\begin{table}[!t]",
        "\\centering",
        f"\\caption{{Maintenance policies evaluated on the same {num(n)} simulated pipelines over a 20-yr horizon"
        " (expected discounted cost, k\\$, $\\pm$ Monte Carlo s.e.)}",
        "\\label{tab:maint}",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\begin{tabular}{lcccccc}",
        "\\toprule",
        " & \\multicolumn{4}{c}{Cost-minimizing policy} & \\multicolumn{2}{c}{$I=2$, $\\gamma=1.5$} \\\\",
        "\\cmidrule(lr){2-5}\\cmidrule(lr){6-7}",
        "Decision model & $I^*$ (yr) & $\\gamma^*$ (yr) & Cost & Fail.\\ (\\%) & Cost & Fail.\\ (\\%) \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\\\[2pt]\\footnotesize{Fail.: share of pipelines with at least one failure within the horizon.}",
        "\\end{table}",
    ])


def main():
    out = ["% Generated by experiments/make_latex.py from results/*.json. Requires \\usepackage{booktabs}.",
           "% Scenario B (heterogeneous, drifting parameters) is the main experiment; scenario A (every",
           "% pipeline has the Table IV parameters) carries labels prefixed tab:A- for an optional comparison.",
           ""]
    for scen in ("B", "A"):
        block = []
        f = ROOT / "results" / f"table6_{scen}.json"
        if f.exists():
            res = json.loads(f.read_text())
            block += [f"% ---- Scenario {scen} ----", table6(res), "", table7(res), ""]
        f = ROOT / "results" / f"maintenance_{scen}_full.json"  # extended grid, from extend_gamma.py
        if not f.exists():
            f = ROOT / "results" / f"maintenance_{scen}.json"
        if f.exists():
            block += [f"% ---- Maintenance, scenario {scen} ----", maintenance(json.loads(f.read_text())), ""]
        if scen == "A":
            block = [b.replace("\\label{tab:", "\\label{tab:A-").replace("\\ref{tab:", "\\ref{tab:A-") for b in block]
        out += block
    (ROOT / "results" / "latex_tables.tex").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    sys.exit(main())
